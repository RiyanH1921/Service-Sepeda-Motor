import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';

test.describe.configure({ mode: 'serial' });
test('alur lengkap: kendaraan, nota lama, pencarian, koreksi, pengingat, CSV, dan persistensi', async ({ page, request }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { window.showSaveFilePicker = undefined; });
  await page.goto('/');
  await expect(page.getByText('Setiap perjalanan baik')).toBeVisible();
  await page.screenshot({ path: 'docs/screenshots/web-kosong.png', fullPage: true });
  const navigate = async label => page.getByRole('navigation', { name: 'Navigasi utama' }).getByRole('link', { name: new RegExp(`^${label}`) }).click();

  await test.step('tambah dua motor dan pisahkan datanya', async () => {
    await page.getByRole('button', { name: 'Tambah kendaraan', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nama kendaraan').fill('Vario Biru Tua');
    await dialog.getByLabel(/^Pelat nomor/).fill('W 6299 BY');
    await dialog.getByLabel(/^Odometer awal/).fill('14500');
    await dialog.getByRole('button', { name: 'Simpan kendaraan' }).click();
    await expect(dialog).toHaveCount(0);
    await navigate('Kendaraan saya');
    await page.getByRole('button', { name: 'Tambah kendaraan', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nama kendaraan').fill('Fazzio Putih');
    await dialog.getByLabel(/^Pelat nomor/).fill('B 1234 UJI');
    await dialog.getByRole('button', { name: 'Simpan kendaraan' }).click();
    await expect(page.getByRole('heading', { name: 'Fazzio Putih' })).toBeVisible();
    await navigate('Garasi');
  });
  await test.step('simpan servis terbaru dan nota lama tanpa mengganti yang terbaru', async () => {
    await page.getByRole('button', { name: 'Catat servis', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Tanggal servis').fill('2026-11-19');
    await dialog.getByLabel(/^Odometer \(opsional\)/).fill('14500');
    await dialog.getByText('Ganti kampas rem', { exact: true }).click();
    await dialog.getByText('Periksa ban', { exact: true }).click();
    await dialog.getByLabel(/^Total biaya/).fill('120000');
    await dialog.getByLabel('Bengkel', { exact: true }).fill('Bengkel Bintang 99');
    await dialog.getByRole('button', { name: 'Simpan servis' }).click();
    await expect(page.locator('.latest-card h2')).toHaveText('19 November 2026');
    await page.getByRole('button', { name: 'Catat servis', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Tanggal servis').fill('2026-08-10');
    await dialog.getByLabel(/^Odometer \(opsional\)/).fill('12000');
    await dialog.getByText('Ganti oli mesin', { exact: true }).click();
    await dialog.getByLabel(/^Total biaya/).fill('0');
    await dialog.getByLabel('Bengkel', { exact: true }).fill('Bengkel, "A"');
    await dialog.getByLabel('Catatan', { exact: true }).fill('Baris satu\nBaris dua');
    await dialog.getByRole('button', { name: 'Simpan servis' }).click();
    await expect(page.locator('.latest-card h2')).toHaveText('19 November 2026');
    const state = await (await request.get('/api/state')).json();
    expect(state.visits).toHaveLength(2);
    expect(state.vehicles[0].odometerKm).toBe(14500);
    await page.screenshot({ path: 'docs/screenshots/web-garasi.png', fullPage: true });
  });
  await test.step('cari OLI, buka detail, koreksi bengkel, dan uji hasil kosong', async () => {
    await navigate('Riwayat servis');
    const search = page.getByRole('textbox', { name: 'Cari pekerjaan atau bengkel' });
    await search.fill('OLI');
    await expect(page.locator('.history-card')).toHaveCount(1);
    await page.screenshot({ path: 'docs/screenshots/web-riwayat.png', fullPage: true });
    await page.locator('.history-card').click();
    await expect(page.getByRole('dialog').getByText('Gratis', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Ubah catatan', exact: true }).click();
    await page.getByRole('dialog').getByLabel('Bengkel', { exact: true }).fill('Bengkel Baru');
    await page.getByRole('dialog').getByRole('button', { name: 'Simpan servis' }).click();
    await search.fill('baru');
    await expect(page.locator('.history-card')).toHaveCount(1);
    await search.fill('tidak-ada-sama-sekali');
    await expect(page.getByRole('heading', { name: 'Servis tidak ditemukan' })).toBeVisible();
    await page.getByRole('button', { name: 'Hapus pencarian', exact: true }).last().click();
    await expect(search).toHaveValue('');
    const state = await (await request.get('/api/state')).json();
    await page.getByRole('combobox', { name: 'Kendaraan aktif' }).selectOption(state.vehicles[1].id);
    await expect(page.getByRole('heading', { name: 'Belum ada servis tercatat' })).toBeVisible();
    await page.getByRole('combobox', { name: 'Kendaraan aktif' }).selectOption(state.vehicles[0].id);
  });
  await test.step('pilih komponen, batalkan perubahan pilihan, dan capai target km', async () => {
    await navigate('Pengingat');
    await page.getByRole('button', { name: 'Tambah pengingat', exact: true }).click();
    await page.getByRole('button', { name: 'Pilih komponen', exact: true }).click();
    const picker = page.getByRole('dialog').last();
    await picker.getByRole('textbox', { name: 'Cari komponen' }).fill('oli');
    await picker.getByRole('radio', { name: 'Oli mesin', exact: true }).check();
    await picker.getByRole('button', { name: 'Gunakan pilihan' }).click();
    await page.getByRole('button', { name: 'Oli mesin', exact: true }).click();
    await page.getByRole('dialog').last().getByRole('radio', { name: 'Ban', exact: true }).check();
    await page.getByRole('dialog').last().getByRole('button', { name: 'Batal', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Oli mesin', exact: true })).toBeVisible();
    const form = page.getByRole('dialog');
    await form.getByLabel('Tanggal target (opsional)').fill('2027-01-18');
    await form.getByLabel(/^Target kilometer/).fill('16500');
    await form.getByRole('button', { name: 'Simpan pengingat' }).click();
    await navigate('Kendaraan saya');
    await page.getByRole('button', { name: 'Perbarui kilometer', exact: true }).click();
    await page.getByRole('dialog').getByLabel(/^Odometer baru/).fill('14000');
    await page.getByRole('dialog').getByRole('button', { name: 'Simpan kilometer' }).click();
    await expect(page.getByRole('dialog').getByRole('alert')).toContainText('14.500');
    await page.getByRole('dialog').getByLabel(/^Odometer baru/).fill('16500');
    await page.getByRole('dialog').getByRole('button', { name: 'Simpan kilometer' }).click();
    await navigate('Pengingat');
    await expect(page.locator('.reminder-card .status-badge')).toHaveText('Jatuh tempo');
    await page.screenshot({ path: 'docs/screenshots/web-pengingat.png', fullPage: true });
  });
  await test.step('ekspor, impor identik, impor rusak, dan tolak izin notifikasi', async () => {
    await navigate('Pengaturan');
    const downloading = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Ekspor CSV', exact: true }).click();
    const download = await downloading;
    expect(download.suggestedFilename()).toMatch(/buku-servis-.*\.csv$/);
    await download.saveAs(resolve('.tools/web-test-export.csv'));
    const csv = await (await request.get('/api/export')).text();
    await page.getByLabel('Berkas impor CSV').setInputFiles({ name: 'riwayat.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
    await expect(page.locator('.import-result')).toContainText('0 kunjungan diimpor, 2 kunjungan identik dilewati');
    await page.getByLabel('Berkas impor CSV').setInputFiles({ name: 'rusak.csv', mimeType: 'text/csv', buffer: Buffer.from(csv + 'baris,rusak\n') });
    await expect(page.locator('.settings-section .form-error')).toContainText('Baris');
    expect((await (await request.get('/api/state')).json()).visits).toHaveLength(2);
    await page.evaluate(() => Object.defineProperty(window, 'Notification', { configurable: true, value: class { static permission = 'denied'; static async requestPermission() { return 'denied'; } } }));
    await page.getByRole('switch', { name: 'Notifikasi servis' }).click();
    await expect(page.getByRole('switch', { name: 'Notifikasi servis' })).toHaveAttribute('aria-checked', 'false');
    await expect(page.getByRole('alert').filter({ hasText: 'Izin notifikasi' })).toBeVisible();
    await page.screenshot({ path: 'docs/screenshots/web-pengaturan.png', fullPage: true });
  });
  await page.reload();
  await navigate('Garasi');
  await expect(page.locator('.latest-card h2')).toHaveText('19 November 2026');
  expect(errors).toEqual([]);
});

test('tampilan ponsel dan formulir dapat digunakan tanpa gulir horizontal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#garasi');
  await expect(page.getByRole('heading', { name: 'Garasi Riyan' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'docs/screenshots/web-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Catat servis', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Catatan', { exact: true }).fill('Menguji formulir pada layar kecil.');
  await dialog.getByRole('button', { name: 'Simpan servis' }).scrollIntoViewIfNeeded();
  await expect(dialog.getByRole('button', { name: 'Simpan servis' })).toBeVisible();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy();
  await page.screenshot({ path: 'docs/screenshots/web-form-mobile.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Batal', exact: true }).click();
  await page.getByRole('navigation', { name: 'Navigasi ponsel' }).getByRole('link', { name: 'Riwayat', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Riwayat servis', exact: true })).toBeVisible();
});
